const DEGREE: [u8; 5] = [0x00, 0x06, 0x09, 0x09, 0x06];

pub const CELL: usize = 8;
pub const COLS: usize = 16;
pub const ATLAS_W: usize = COLS * CELL;
pub const ATLAS_H: usize = 8 * CELL;
pub const GLYPH_W: f32 = 5.0;
pub const GLYPH_H: f32 = 7.0;
pub const ADVANCE: f32 = 6.0;
/// Cell index of a solid block used for untextured fills.
pub const SOLID: usize = 96;
const DEGREE_CELL: usize = 97;

pub fn cell_for(ch: char) -> usize {
    match ch {
        ' '..='~' => ch as usize - 32,
        '°' => DEGREE_CELL,
        '−' | '–' | '—' => '-' as usize - 32,
        '′' => '\'' as usize - 32,
        '″' => '"' as usize - 32,
        _ => '?' as usize - 32,
    }
}

/// White RGBA atlas; alpha carries the glyph mask.
pub fn atlas() -> Vec<u8> {
    let mut px = vec![0u8; ATLAS_W * ATLAS_H * 4];
    let mut put = |cell: usize, cols: &[u8; 5]| {
        let (cx, cy) = ((cell % COLS) * CELL, (cell / COLS) * CELL);
        for (x, &col) in cols.iter().enumerate() {
            for y in 0..7 {
                if col >> y & 1 == 1 {
                    let i = ((cy + y) * ATLAS_W + cx + x) * 4;
                    px[i..i + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    };
    for (i, g) in GLYPHS.iter().enumerate() {
        put(i, g);
    }
    put(DEGREE_CELL, &DEGREE);
    let (cx, cy) = ((SOLID % COLS) * CELL, (SOLID / COLS) * CELL);
    for y in 0..CELL {
        for x in 0..CELL {
            let i = ((cy + y) * ATLAS_W + cx + x) * 4;
            px[i..i + 4].copy_from_slice(&[255, 255, 255, 255]);
        }
    }
    px
}

/// Texture coordinates (u0, v0, u1, v1) for a glyph's 5x7 box.
pub fn glyph_uv(cell: usize) -> (f32, f32, f32, f32) {
    let (cx, cy) = ((cell % COLS) * CELL, (cell / COLS) * CELL);
    (
        cx as f32 / ATLAS_W as f32,
        cy as f32 / ATLAS_H as f32,
        (cx as f32 + GLYPH_W) / ATLAS_W as f32,
        (cy as f32 + GLYPH_H) / ATLAS_H as f32,
    )
}

pub fn solid_uv() -> (f32, f32) {
    let (cx, cy) = ((SOLID % COLS) * CELL, (SOLID / COLS) * CELL);
    ((cx as f32 + 4.0) / ATLAS_W as f32, (cy as f32 + 4.0) / ATLAS_H as f32)
}
